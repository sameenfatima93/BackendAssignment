// Two number variables
let num1 = 20;
let num2 = 5;


// ---------- Arithmetic Operators ----------

console.log("Addition:", num1 + num2);
console.log("Subtraction:", num1 - num2);
console.log("Multiplication:", num1 * num2);
console.log("Division:", num1 / num2);
console.log("Modulus:", num1 % num2);


// Increment
let incrementNumber = 10;
incrementNumber++;

console.log("Increment:", incrementNumber);


// Decrement
let decrementNumber = 10;
decrementNumber--;

console.log("Decrement:", decrementNumber);


// ---------- Assignment Operators ----------

let number = 20;

console.log("Initial value:", number);

// =
number = 30;
console.log("After = :", number);

// +=
number += 10;
console.log("After += :", number);

// -=
number -= 5;
console.log("After -= :", number);

// *=
number *= 2;
console.log("After *= :", number);

// /=
number /= 5;
console.log("After /= :", number);


// ---------- Comparison Operators ----------

let value1 = 10;
let value2 = 10;
let value3 = "10";

console.log("value1 == value2:", value1 == value2);
console.log("value1 === value3:", value1 === value3);
console.log("value1 != value3:", value1 != value3);
console.log("value1 !== value3:", value1 !== value3);
console.log("value1 > 5:", value1 > 5);
console.log("value1 < 20:", value1 < 20);
console.log("value1 >= 10:", value1 >= 10);
console.log("value1 <= 10:", value1 <= 10);